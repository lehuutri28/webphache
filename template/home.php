(function(){
  function stopAllVideos(except){
    document.querySelectorAll('.youtube-frame, .catcard-thumb, .short-card, .intro-v9-video').forEach(function(el){
      if(el===except) return;
      var iframe=el.querySelector('iframe');
      if(!iframe) return;
      iframe.remove();
      el.querySelectorAll('img').forEach(function(img){img.style.opacity='';img.style.display='';});
      el.querySelectorAll('.play-button,.catcard-play-ico,.short-play,.intro-v9-play,.intro-v9-vtitle').forEach(function(e){e.style.display='';});
      if(!el.querySelector('img') && el.dataset && el.dataset.embed){
        var img=document.createElement('img');
        img.src='https://img.youtube.com/vi/'+el.dataset.embed+'/hqdefault.jpg';
        img.style.cssText='width:100%;height:100%;object-fit:cover;position:absolute;top:0;left:0;opacity:.85;';
        el.insertBefore(img,el.firstChild);
      }
    });
  }

  function playInline(container, vid){
    if(container.querySelector('iframe')){container.querySelector('iframe').remove();return;}
    stopAllVideos(container);
    container.querySelectorAll('img').forEach(function(img){img.style.opacity='0';});
    container.querySelectorAll('.play-button,.catcard-play-ico,.short-play,.recap-card-title,.intro-v9-play,.intro-v9-vtitle').forEach(function(el){el.style.display='none';});
    var iframe=document.createElement('iframe');
    iframe.src='https://www.youtube.com/embed/'+vid+'?autoplay=1&rel=0&showinfo=0';
    iframe.setAttribute('frameborder','0');
    iframe.setAttribute('allowfullscreen','');
    iframe.setAttribute('allow','autoplay;encrypted-media');
    iframe.style.cssText='position:absolute;top:0;left:0;width:100%;height:100%;border:0;z-index:5;';
    container.appendChild(iframe);
  }

  window.playCatVid=function(card,vid){
    var thumb=card.querySelector('.catcard-thumb,.intro-v9-video,.short-card')||card;
    playInline(thumb,vid);
  };

  window.addEventListener('load',function(){
    document.querySelectorAll('.youtube-frame[data-embed]').forEach(function(frame){
      var clone=frame.cloneNode(true);
      frame.parentNode.replaceChild(clone,frame);
      clone.addEventListener('click',function(e){
        e.preventDefault();e.stopPropagation();
        playInline(this,this.dataset.embed);
      });
    });
  });
})();
