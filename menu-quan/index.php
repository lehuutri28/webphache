// 2. Interactive Simulator Tính Cost
var simPrice = 35000;
var simRent = 15000000;

function updateSimPrice(val) {
  simPrice = parseInt(val, 10);
  document.getElementById('sim-price-val').textContent = simPrice.toLocaleString('vi-VN') + ' đ';
  calculateSimCost();
}

function updateSimRent(val) {
  simRent = parseInt(val, 10);
  document.getElementById('sim-rent-val').textContent = simRent.toLocaleString('vi-VN') + ' đ';
  calculateSimCost();
}

function calculateSimCost() {
  var type = document.getElementById('sim-drink-type').value;
  var costPercent = 0.20; // mặc định trà sữa 20%
  if(type === 'ca-phe') costPercent = 0.18;
  else if(type === 'tra-trai-cay') costPercent = 0.22;
  else if(type === 'da-xay') costPercent = 0.24;

  var costVal = Math.round(simPrice * costPercent);
  var profitVal = simPrice - costVal;
  var profitPercent = Math.round((profitVal / simPrice) * 100);

  // Số ly để hòa vốn mặt bằng (30 ngày)
  var dailyRent = simRent / 30;
  var breakevenCups = Math.ceil(dailyRent / profitVal);

  // Doanh thu khi bán 120 ly/ngày
  var monthlyRev = simPrice * 120 * 30;

  document.getElementById('sim-res-cost').textContent = costVal.toLocaleString('vi-VN') + ' đ (' + Math.round(costPercent * 100) + '%)';
  document.getElementById('sim-res-profit').textContent = profitVal.toLocaleString('vi-VN') + ' đ (' + profitPercent + '%)';
  document.getElementById('sim-res-breakeven').textContent = breakevenCups + ' ly/ngày';
  document.getElementById('sim-res-rev').textContent = monthlyRev.toLocaleString('vi-VN') + ' đ/tháng';
}

